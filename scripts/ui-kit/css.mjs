const DIR = '../assets/ui-kit';
const url = (name) => `url('${DIR}/${name}.png')`;
const px = (n) => `${n}px`;

/** `border-image` rule for a 9-slice picture: slice in picture px, drawn at 1 art px = 1 css px (the stage scales it). */
function ninePatch(name, [t, r, b, l]) {
  return [
    'box-sizing: border-box;',
    'border-style: solid;',
    'border-color: transparent;',
    `border-width: ${px(t)} ${px(r)} ${px(b)} ${px(l)};`,
    `border-image: ${url(name)} ${t} ${r} ${b} ${l} fill / ${px(t)} ${px(r)} ${px(b)} ${px(l)} stretch;`,
    'image-rendering: pixelated;',
  ];
}

const rule = (selector, lines) => `${selector} {\n${lines.map((line) => `  ${line}`).join('\n')}\n}`;

/** The stylesheet for the kit: one class per element (`.px-<name>`), buttons with their pressed and disabled pictures. */
export function renderCss(kit) {
  const byName = new Map(kit.map((e) => [e.name, e]));
  const out = ['/* GENERATED by scripts/gen-ui-kit.mjs from scripts/ui-kit/spec.mjs. Do not edit by hand. */', ''];
  const buttons = new Set();
  for (const e of kit) {
    const m = e.name.match(/^button-(\w+)-(l|s)-normal$/);
    if (m) buttons.add(`${m[1]}-${m[2]}`);
  }
  out.push(
    rule('.px-button', [
      'display: flex;',
      'align-items: center;',
      'justify-content: center;',
      'padding: 0 2px;',
      'background: none;',
      'color: inherit;',
      'font: inherit;',
      'text-shadow: 1px 1px 0 #1b1426;',
      'cursor: pointer;',
      '-webkit-tap-highlight-color: transparent;',
    ]),
    rule('.px-button:active:not(:disabled) > span, .px-button.is-pressed > span', ['transform: translateY(1px);']),
    rule('.px-button:disabled, .px-button[aria-disabled="true"]', ['cursor: default;', 'color: #b8b8c8;']),
    rule('.px-button:disabled > span', ['transform: none;']),
    '',
  );
  for (const key of buttons) {
    const normal = byName.get(`button-${key}-normal`);
    const cls = `.px-button-${key}`;
    out.push(rule(cls, [...ninePatch(`button-${key}-normal`, normal.slice), `height: ${px(normal.h)};`]));
    out.push(rule(`${cls}:active:not(:disabled), ${cls}.is-pressed`, [`border-image-source: ${url(`button-${key}-pressed`)};`]));
    out.push(rule(`${cls}:disabled, ${cls}[aria-disabled="true"]`, [`border-image-source: ${url(`button-${key}-disabled`)};`]));
  }
  out.push('');
  for (const e of kit) {
    if (!e.slice || e.name.startsWith('button-')) continue;
    out.push(rule(`.px-${e.name}`, ninePatch(e.name, e.slice)));
  }
  out.push('');
  for (const name of ['close', 'arrow-left', 'arrow-right']) {
    const e = byName.get(`${name}-normal`);
    out.push(
      rule(`.px-${name}`, ['display: block;', 'padding: 0;', 'border: 0;', `width: ${px(e.w)};`, `height: ${px(e.h)};`, `background: ${url(`${name}-normal`)} 0 0 / ${px(e.w)} ${px(e.h)} no-repeat;`, 'image-rendering: pixelated;', 'cursor: pointer;', '-webkit-tap-highlight-color: transparent;']),
      rule(`.px-${name}:active, .px-${name}.is-pressed`, [`background-image: ${url(`${name}-pressed`)};`]),
    );
  }
  for (const e of kit.filter((x) => x.name.startsWith('icon-'))) {
    out.push(rule(`.px-${e.name}`, ['display: inline-block;', 'vertical-align: middle;', `width: ${px(e.w)};`, `height: ${px(e.h)};`, `background: ${url(e.name)} 0 0 / ${px(e.w)} ${px(e.h)} no-repeat;`, 'image-rendering: pixelated;']));
  }
  for (const direction of ['up', 'down']) {
    const e = byName.get(`tip-arrow-${direction}`);
    out.push(rule(`.px-tip-arrow-${direction}`, ['display: block;', `width: ${px(e.w)};`, `height: ${px(e.h)};`, `background: ${url(`tip-arrow-${direction}`)} 0 0 / ${px(e.w)} ${px(e.h)} no-repeat;`, 'image-rendering: pixelated;']));
  }
  return `${out.join('\n')}\n`;
}
